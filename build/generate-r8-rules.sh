#!/bin/sh
# Regenerates the consumer R8/ProGuard keep-rules every package ships:
# src/<PackageId>/buildTransitive/<PackageId>.pro, one per row in build/packages.tsv. Run it
# after bumping SfmcNativeVersion; CI re-runs it and fails on a diff, so a stale committed file
# cannot ship.
#
# Why the rules exist at all:
#
#   1. .NET for Android never feeds an .aar's embedded proguard.txt to R8 - upstream's consumer
#      rules are silently lost, so this script recovers them from every shipped .aar verbatim.
#
#   2. A binding's Java side is reached from C# through JNI lookups by name, which R8 cannot
#      see. The curated section keeps the JNI-only entry surface; everything deeper survives
#      through ordinary reference reachability from there.
#
# The .aars are downloaded from Salesforce's repository and verified against
# build/maven-checksums.txt BEFORE anything is read out of them.
set -eu

root="$(cd "$(dirname "$0")/.." && pwd)"
work="$(mktemp -d)"
trap 'rm -rf "$work"' EXIT

repo="https://salesforce-marketingcloud.github.io/MarketingCloudSDK-Android/repository"
group_path="com/salesforce/marketingcloud"

prop() {
    sed -n "s/.*<$1>\(.*\)<\/$1>.*/\1/p" "$root/Directory.Build.props" | head -1
}

fetch_verified() {
    file="$1-$2.aar"
    curl -fsSL -o "$work/$file" "$repo/$group_path/$1/$2/$file"
    pinned="$(grep "^$file " "$root/build/maven-checksums.txt" | cut -d' ' -f2)"
    actual="$(shasum -a 256 "$work/$file" | cut -d' ' -f1)"
    if [ -z "$pinned" ] || [ "$pinned" != "$actual" ]; then
        echo "error: $file does not match build/maven-checksums.txt (pinned: '$pinned', actual: '$actual')" >&2
        exit 1
    fi
}

extract_consumer_rules() {
    file="$1-$2.aar"
    if unzip -p "$work/$file" proguard.txt > "$work/$1-proguard.txt" 2>/dev/null && [ -s "$work/$1-proguard.txt" ]; then
        {
            echo "# ---- upstream consumer rules ($file proguard.txt), shipped verbatim ----"
            cat "$work/$1-proguard.txt"
            echo
        } >> "$3"
    else
        echo "# ---- $file ships no proguard.txt ----" >> "$3"
    fi
}

out="$root/src/MarketingCloudSDK.Net.Android/buildTransitive/MarketingCloudSDK.Net.Android.pro"

cat > "$out" <<'EOF'
# Generated by build/generate-r8-rules.sh - do not edit by hand; edit the script and re-run.
#
# Keep-rules for consuming Android applications that build with R8 (AndroidLinkTool=r8).
# See the .targets alongside for why .NET for Android needs these shipped explicitly.

EOF

artifacts="marketingcloudsdk $(prop SfmcNativeVersion)
pushfeaturemodule $(prop SfmcPushFeatureVersion)
pushmodelsmodule $(prop SfmcPushModelsVersion)
inappmessagingfeaturemodule $(prop SfmcInAppMessagingFeatureVersion)
inappmessagingmodelsmodule $(prop SfmcInAppMessagingModelsVersion)
common $(prop SfmcCommonVersion)
legacy-crypto $(prop SfmcLegacyCryptoVersion)"

echo "$artifacts" | while IFS=' ' read -r artifact version; do
    [ -n "$artifact" ] || continue
    fetch_verified "$artifact" "$version"
    extract_consumer_rules "$artifact" "$version" "$out"
done

cat >> "$out" <<'EOF'
# ---- curated: the JNI-only entry surface C# reaches (invisible to R8) ----

# The SDK entry points and configuration builders are constructed and called only from C#.
-keep class com.salesforce.marketingcloud.MarketingCloudSdk { *; }
-keep class com.salesforce.marketingcloud.MarketingCloudConfig { *; }
-keep class com.salesforce.marketingcloud.MarketingCloudConfig$Builder { *; }
-keep class com.salesforce.marketingcloud.InitializationStatus { *; }

# The public feature surfaces driven from C# on instances the SDK hands out. Keeping the
# interfaces keeps their implementations on live classes.
-keep class com.salesforce.marketingcloud.notifications.** { *; }
-keep class com.salesforce.marketingcloud.registration.** { *; }
-keep class com.salesforce.marketingcloud.messages.** { *; }
EOF

# Typo guard: every curated '-keep class X' without a wildcard must exist in one of the .aars.
classes="$work/classes.txt"
: > "$classes"
for aar in "$work"/*.aar; do
    unzip -o -q "$aar" classes.jar -d "$work/$(basename "$aar" .aar)-x" 2>/dev/null || continue
    unzip -l "$work/$(basename "$aar" .aar)-x/classes.jar" | awk '{print $4}' | grep '\.class$' >> "$classes" || true
done
grep '^-keep class ' "$out" | sed 's/^-keep class \([^ ]*\) .*$/\1/' | grep -v '\*' | while read -r cls; do
    path="$(echo "$cls" | tr '.' '/').class"
    if ! grep -qF "$path" "$classes"; then
        echo "error: curated keep-rule names $cls, which exists in no verified .aar - a typo or an upstream removal" >&2
        exit 1
    fi
done

echo "==> wrote $out"
